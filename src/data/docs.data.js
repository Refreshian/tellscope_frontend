/**
 * Возвращает статью справки для пути.
 * Сначала ищем точное совпадение, затем — самый длинный префикс маршрута
 * (чтобы работало для вложенных адресов вида /data-set/:folder).
 */
export const getDocForPath = (pathname = '') => {
	const clean = pathname.replace(/\/+$/, '') || '/';

	const exact = PAGE_DOCS.find(doc => doc.path === clean);
	if (exact) return exact;

	let best = null;
	for (const doc of PAGE_DOCS) {
		if (doc.path === '/') continue;
		if (clean.startsWith(`${doc.path}/`) || clean === doc.path) {
			if (!best || doc.path.length > best.path.length) best = doc;
		}
	}
	return best;
};
